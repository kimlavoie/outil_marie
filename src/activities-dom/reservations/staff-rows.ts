import { getSalaries, getSalaryById } from "../../state/settings-repository.ts";
import { formatCurrency, generateUid, rejectNegativeAmountOnBlur, maskTimeInput, calculateHoursFromTimes, maskDateInput, debounce } from "../../utils/utils.ts";
import { updateSubmissionFinancialSummary, autoSaveActivityForm } from "../financials.ts";
import { el, getEarliestSlotDateFromDom } from "./row-dom-helpers.ts";
